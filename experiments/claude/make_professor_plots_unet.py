def _fit_power_law(ns, rl2s):
    n = np.asarray(ns, float); r = np.asarray(rl2s, float)
    ok = np.isfinite(n) & np.isfinite(r) & (n > 0) & (r > 0)
    if ok.sum() < 2: return None
    sl, ic, rv, _, _ = linregress(np.log(n[ok]), np.log(r[ok]))
    a, b = np.exp(ic), sl
    nstar = lambda thr: float("nan") if b >= 0 else float((thr / a) ** (1.0 / b))
    return dict(a=a, b=b, r2=rv**2, n_star_10=nstar(0.10), n_star_5=nstar(0.05))


