# FIGURE 4 — Predictions, organised by frequency pair
#
# Layout:  3 pair-groups  (16↔32 / 32↔64 / 64↔128)
#          Within each group: 2 rows  (low→high  /  high→low)
#          5 columns:  input Re  |  target Re  |  prediction Re  |  |error|/σ  |  metrics
# ══════════════════════════════════════════════════════════════════════════════
def make_fig4():
    """
    Columns reflect what the UNet encoder-decoder actually does:

      [Encoder input Re] | [Encoder input Im]
      ↓  compressed by encoder, reconstructed by decoder  ↓
      [GT Re]  [Pred Re]  |  [GT Im]  [Pred Im]  |  Complex error

    Reading left-to-right is the UNet pipeline:
      what goes in → what the decoder must produce (both channels) → how wrong it is.

    Rows: 3 frequency pairs × 2 directions, grouped by pair.
    Metrics embedded in row labels (no separate metrics column).
    """
    print("  Building Fig 4: UNet encoder→decoder predictions …")
    model_up = load_unet(CKPT_UP)
    model_dn = load_unet(CKPT_DOWN)
    raw_up   = get_test_raw_indices()
    raw_down = get_test_raw_indices()

    ROWS = [
        (DS_UP,   raw_up[0],   "up",   16,  32,  model_up, r"16$\rightarrow$32",  0),
        (DS_DOWN, raw_down[0], "down", 32,  16,  model_dn, r"32$\rightarrow$16",  0),
        (DS_UP,   raw_up[1],   "up",   32,  64,  model_up, r"32$\rightarrow$64",  1),
        (DS_DOWN, raw_down[1], "down", 64,  32,  model_dn, r"64$\rightarrow$32",  1),
        (DS_UP,   raw_up[2],   "up",   64,  128, model_up, r"64$\rightarrow$128", 2),
        (DS_DOWN, raw_down[2], "down", 128, 64,  model_dn, r"128$\rightarrow$64", 2),
    ]

    # ── inference ─────────────────────────────────────────────────────────────
    samples = []
    for ds, raw_idx, direction, w_in, w_out, model, row_lbl, pair_grp in ROWS:
        print(f"    ω {row_lbl} …")
        u_low_re, u_low_im, u_high_re, u_high_im, omega = load_raw(ds, raw_idx)
        if direction == "up":
            inp_re, inp_im = u_low_re,  u_low_im
            tgt_re, tgt_im = u_high_re, u_high_im
            triv_re        = u_low_re
        else:
            inp_re, inp_im = u_high_re, u_high_im
            tgt_re, tgt_im = u_low_re,  u_low_im
            triv_re        = u_high_re

        pred    = infer(model, build_input(inp_re, inp_im, omega))
        pred_re = pred[0]; pred_im = pred[1]

        # Complex error: magnitude over both channels, normalised by σ of target Re
        sigma    = float(np.std(tgt_re[SL, SL])) + 1e-8
        err_cplx = np.sqrt((pred_re - tgt_re) ** 2 + (pred_im - tgt_im) ** 2) / sigma

        # RelL2 over Re and Im jointly (complex RRMSE, interior only)
        diff_re = (pred_re - tgt_re)[SL, SL].ravel()
        diff_im = (pred_im - tgt_im)[SL, SL].ravel()
        norm_re = tgt_re[SL, SL].ravel(); norm_im = tgt_im[SL, SL].ravel()
        cplx_rrmse = float(
            np.sqrt(np.sum(diff_re**2 + diff_im**2)) /
            (np.sqrt(np.sum(norm_re**2 + norm_im**2)) + 1e-8) * 100
        )
        triv_rrmse = rel_l2(triv_re, tgt_re)

        samples.append(dict(
            inp_re=inp_re, inp_im=inp_im,
            tgt_re=tgt_re, tgt_im=tgt_im,
            pred_re=pred_re, pred_im=pred_im,
            err_cplx=err_cplx,
            row_lbl=row_lbl, pair_grp=pair_grp, direction=direction,
            cplx_rrmse=cplx_rrmse, triv_pct=triv_rrmse,
        ))

    # ── shared colour limits ───────────────────────────────────────────────────
    # Input channels share a scale; GT/pred channels share a (separate) scale
    v_in  = max(max(float(np.abs(s["inp_re"]).max()),
                    float(np.abs(s["inp_im"]).max())) for s in samples) * 1.02
    v_out = max(max(float(np.abs(s["tgt_re"]).max()),
                    float(np.abs(s["tgt_im"]).max()),
                    float(np.abs(s["pred_re"]).max()),
                    float(np.abs(s["pred_im"]).max())) for s in samples) * 1.02
    emax  = min(max(float(s["err_cplx"].max()) for s in samples), 3.0)

    kw_in  = dict(vmin=-v_in,  vmax=v_in,  cmap=CMAP_FIELD, origin="lower")
    kw_out = dict(vmin=-v_out, vmax=v_out, cmap=CMAP_FIELD, origin="lower")
    kw_err = dict(vmin=0,      vmax=emax,  cmap=CMAP_ERR,   origin="lower")

    # ── layout: 6 rows × 6 columns ────────────────────────────────────────────
    #
    #  Col 0        Col 1        | Col 2       Col 3       | Col 4       Col 5
    #  Re(u_in)     Im(u_in)     | Re(u_tgt)   Re(û)       | Im(u_tgt)   Im(û)
    #  ──── ENCODER INPUT ─────  | ──── REAL PART ────────  | ── IMAGINARY PART ──
    #                             └──────────── DECODER OUTPUT vs TARGET ─────────┘
    #   + Col 6: complex error
    #
    NCOLS = 7
    NROWS = 6
    fig = plt.figure(figsize=(NCOLS * 3.0, NROWS * 2.7), constrained_layout=True)
    # Slight extra width for error col; keep input cols same as output cols
    gs  = gridspec.GridSpec(NROWS, NCOLS, figure=fig,
                            width_ratios=[1, 1, 1, 1, 1, 1, 1])

    PAIR_LABELS = ["ω = 16 ↔ 32", "ω = 32 ↔ 64", "ω = 64 ↔ 128"]
    pair_color  = ["#1A5276", "#1E8449", "#7D6608"]

    # Column header groups drawn as coloured bands above row 0
    COL_GROUPS = [
        (0, 1, "#D5D8DC", "Encoder input\n(both channels fed to network)"),
        (2, 3, "#D6EAF8", "Real part  Re(u)\nGround truth  |  UNet prediction"),
        (4, 5, "#FDEBD0", "Imaginary part  Im(u)\nGround truth  |  UNet prediction"),
        (6, 6, "#FDEDEC", "Complex error\n|û − u| / σ"),
    ]

    col_titles = [
        r"$\mathrm{Re}(u_\mathrm{in})$",
        r"$\mathrm{Im}(u_\mathrm{in})$",
        r"$\mathrm{Re}(u_\mathrm{out})$" + "\nGround truth",
        r"$\mathrm{Re}(\hat{u})$"         + "\nUNet pred.",
        r"$\mathrm{Im}(u_\mathrm{out})$" + "\nGround truth",
        r"$\mathrm{Im}(\hat{u})$"         + "\nUNet pred.",
        r"$|\hat{u} - u|\,/\,\sigma_u$"  + "\nComplex error",
    ]

    for i, s in enumerate(samples):
        mp = s["cplx_rrmse"]; tp = s["triv_pct"]
        c_m = "#16a34a" if mp < tp else "#dc2626"
        dir_arrow = "↑" if s["direction"] == "up" else "↓"
        pc = pair_color[s["pair_grp"]]

        axs = [fig.add_subplot(gs[i, c]) for c in range(NCOLS)]
        for a in axs: a.set_xticks([]); a.set_yticks([])

        if i == 0:
            for c, a in enumerate(axs):
                a.set_title(col_titles[c], fontsize=7.5, pad=5)

        # Row label: direction + operator + metrics baked in
        axs[0].set_ylabel(
            f"{dir_arrow} ω {s['row_lbl']}\n"
            f"RelL2 {mp:.1f}%  (trivial {tp:.0f}%)",
            fontsize=8, labelpad=5, color=pc,
        )

        _cbar(fig, axs[0].imshow(s["inp_re"],  **kw_in),  axs[0])
        _cbar(fig, axs[1].imshow(s["inp_im"],  **kw_in),  axs[1])
        _cbar(fig, axs[2].imshow(s["tgt_re"],  **kw_out), axs[2])
        _cbar(fig, axs[3].imshow(s["pred_re"], **kw_out), axs[3])
        _cbar(fig, axs[4].imshow(s["tgt_im"],  **kw_out), axs[4])
        _cbar(fig, axs[5].imshow(s["pred_im"], **kw_out), axs[5])
        _cbar(fig, axs[6].imshow(s["err_cplx"],**kw_err), axs[6])

        # Visual dividers between column groups (subtle vertical gap not possible
        # in gridspec, so draw a right-edge line on cols 1 and 5)
        for div_col in (1, 3, 5):
            axs[div_col].plot([1.04, 1.04], [0, 1], color="#999", lw=0.8,
                              transform=axs[div_col].transAxes, clip_on=False)

        # Pair separator after rows 1 and 3
        if i in (1, 3):
            for a in axs:
                a.plot([0, 1], [-0.055, -0.055], color=pc,
                       lw=1.2, ls="--", transform=a.transAxes, clip_on=False)

        # Pair group label on far-left margin (first row of each pair)
        if i % 2 == 0:
            axs[0].text(-0.60, 0.5, PAIR_LABELS[s["pair_grp"]],
                        ha="center", va="center", fontsize=9, fontweight="bold",
                        color=pc, rotation=90, transform=axs[0].transAxes)

    # Column-group header bands above the plot
    group_bg = ["#EAECEE", "#D6EAF8", "#FDEBD0", "#FDEDEC"]
    group_labels = [
        "Encoder input",
        "Real part  —  decoder target vs output",
        "Imaginary part  —  decoder target vs output",
        "Complex\nerror",
    ]
    group_cols = [(0, 1), (2, 3), (4, 5), (6, 6)]
    # Draw as text above col 0 title row using fig.text in axes coords
    ax_refs = [fig.add_subplot(gs[0, c]) for c in range(NCOLS)]  # will overlap — just for coords
    for (c0, c1), bg, lbl in zip(group_cols, group_bg, group_labels):
        # Use a rectangle spanning those columns
        x0 = gs[0, c0].get_position(fig).x0
        x1 = gs[0, c1].get_position(fig).x1
        y1 = gs[0, c0].get_position(fig).y1
        rect = plt.Rectangle((x0, y1 + 0.005), x1 - x0, 0.022,
                              transform=fig.transFigure, clip_on=False,
                              fc=bg, ec="#888", lw=0.5, zorder=3)
        fig.add_artist(rect)
        fig.text((x0 + x1) / 2, y1 + 0.016, lbl,
                 ha="center", va="center", fontsize=7.5, fontweight="bold",
                 color="#333", zorder=4)

    fig.suptitle(
        "ResU-Net: Encoder Input → Decoder Output  —  UMFPACK dataset  (N = 4,800/pair, held-out test)\n"
        "Columns: encoder receives both Re/Im channels simultaneously  |  "
        "decoder outputs both Re/Im channels jointly  |  "
        "rows grouped by frequency pair",
        fontsize=9,
    )
    out = OUT_DIR / "fig4_predictions.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig); print(f"    → {out}")


