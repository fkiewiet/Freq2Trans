#!/usr/bin/env python3
"""Generate exact 2D FD/PML complex-source transfer data.

This is the 2D analogue of the corrected 1D flux/full-data step: u_low and
u_high are generated by the same repository FD/PML Helmholtz operator used in
the warm-start evaluator, and the full complex source is stored.

The pilot is intentionally small first. Generate e.g. 32->64 with 200-500
samples, audit it, then train/evaluate before scaling.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import scipy.sparse.linalg as spla


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from solver import HelmholtzSolver  # noqa: E402


PAIRS = {
    "16_32": (16.0, 32.0),
    "32_64": (32.0, 64.0),
    "64_128": (64.0, 128.0),
}


@dataclass(frozen=True)
class Data2DConfig:
    n: int = 512
    npml: int = 112
    domain_length: float = 1.0
    source_sigma: float = 2.0
    min_sources: int = 3
    max_sources: int = 6
    seed: int = 42

    @property
    def interior_n(self) -> int:
        return self.n - 2 * self.npml

    @property
    def dx(self) -> float:
        return self.domain_length / (self.interior_n - 1)

    @property
    def interior(self) -> tuple[slice, slice]:
        s = slice(self.npml, self.n - self.npml)
        return s, s

    def to_dict(self) -> dict:
        out = asdict(self)
        out["dx"] = self.dx
        out["interior_n"] = self.interior_n
        return out


def gaussian_source(n: int, px: int, py: int, amp: complex, sigma: float) -> np.ndarray:
    xs = np.arange(n, dtype=np.float64)
    x, y = np.meshgrid(xs, xs, indexing="ij")
    return amp * np.exp(-((x - px) ** 2 + (y - py) ** 2) / (2.0 * sigma**2))


def random_source(rng: np.random.Generator, cfg: Data2DConfig) -> tuple[np.ndarray, dict]:
    n_src = int(rng.integers(cfg.min_sources, cfg.max_sources + 1))
    px = rng.integers(cfg.npml, cfg.n - cfg.npml, size=n_src)
    py = rng.integers(cfg.npml, cfg.n - cfg.npml, size=n_src)
    amps = rng.uniform(1.0, 2.0, size=n_src)
    phases = rng.uniform(0.0, 2.0 * np.pi, size=n_src)
    src = np.zeros((cfg.n, cfg.n), dtype=np.complex128)
    for i in range(n_src):
        src += gaussian_source(
            cfg.n,
            int(px[i]),
            int(py[i]),
            amps[i] * np.exp(1j * phases[i]),
            cfg.source_sigma,
        )
    meta = {
        "n_sources": n_src,
        "px": [int(v) for v in px],
        "py": [int(v) for v in py],
        "amps": [float(v) for v in amps],
        "phases": [float(v) for v in phases],
    }
    return src, meta


def build_lu(omega: float, cfg: Data2DConfig):
    solver = HelmholtzSolver(N=cfg.n, n_pml=cfg.npml, omega=omega, dx=cfg.dx)
    return solver, spla.splu(solver._A)


def dataset_name(pair_tag: str, n_samples: int, cfg: Data2DConfig) -> str:
    return f"pair_{pair_tag}_fdpml_complex_source_N{n_samples}_seed{cfg.seed}"


def generate_pair(pair_tag: str, n_samples: int, out_root: Path, cfg: Data2DConfig, force: bool) -> Path:
    omega_l, omega_h = PAIRS[pair_tag]
    out_dir = out_root / dataset_name(pair_tag, n_samples, cfg)
    if out_dir.exists():
        if not force:
            raise FileExistsError(f"Dataset exists: {out_dir}. Use --force to replace.")
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"\n=== Generating {pair_tag} exact FD/PML complex-source dataset ===", flush=True)
    print(f"out_dir={out_dir}", flush=True)
    print(f"n_samples={n_samples} omega_l={omega_l:g} omega_h={omega_h:g}", flush=True)
    print("building low/high operators and LU factors...", flush=True)
    t0 = time.time()
    solver_l, lu_l = build_lu(omega_l, cfg)
    solver_h, lu_h = build_lu(omega_h, cfg)
    print(f"LU factors ready in {time.time() - t0:.1f}s", flush=True)

    shape = (n_samples, cfg.n, cfg.n)
    arrays = {
        "u_low_re": np.zeros(shape, dtype=np.float32),
        "u_low_im": np.zeros(shape, dtype=np.float32),
        "u_high_re": np.zeros(shape, dtype=np.float32),
        "u_high_im": np.zeros(shape, dtype=np.float32),
        "source_re": np.zeros(shape, dtype=np.float32),
        "source_im": np.zeros(shape, dtype=np.float32),
    }
    rms = np.zeros(n_samples, dtype=np.float32)
    omega_low = np.full(n_samples, omega_l, dtype=np.float32)
    source_meta = []

    rng = np.random.default_rng(cfg.seed + int(omega_l) * 1000 + int(omega_h))
    sl = cfg.interior
    t_start = time.time()
    for i in range(n_samples):
        src, meta = random_source(rng, cfg)
        u_l = lu_l.solve(src.reshape(-1)).reshape(cfg.n, cfg.n)
        u_h = lu_h.solve(src.reshape(-1)).reshape(cfg.n, cfg.n)
        scale = max(float(np.sqrt(np.mean(np.abs(u_l[sl]) ** 2))), 1e-10)

        arrays["u_low_re"][i] = (u_l.real / scale).astype(np.float32)
        arrays["u_low_im"][i] = (u_l.imag / scale).astype(np.float32)
        arrays["u_high_re"][i] = (u_h.real / scale).astype(np.float32)
        arrays["u_high_im"][i] = (u_h.imag / scale).astype(np.float32)
        arrays["source_re"][i] = (src.real / scale).astype(np.float32)
        arrays["source_im"][i] = (src.imag / scale).astype(np.float32)
        rms[i] = np.float32(scale)
        source_meta.append(meta)

        if (i + 1) % max(1, min(25, n_samples)) == 0 or i + 1 == n_samples:
            elapsed = time.time() - t_start
            rate = (i + 1) / max(elapsed, 1e-9)
            eta = (n_samples - i - 1) / max(rate, 1e-9)
            print(f"  {i + 1}/{n_samples} elapsed={elapsed:.0f}s eta={eta:.0f}s rate={rate:.2f}/s", flush=True)

    print("saving arrays...", flush=True)
    for name, arr in arrays.items():
        np.save(out_dir / f"{name}.npy", arr)
    np.save(out_dir / "rms.npy", rms)
    np.save(out_dir / "omega_low.npy", omega_low)

    metadata = {
        "dataset_kind": "fdpml_complex_source",
        "direction": "up",
        "pair_tag": pair_tag,
        "omega_l": omega_l,
        "omega_h": omega_h,
        "n_samples": n_samples,
        "config": cfg.to_dict(),
        "normalization": "all fields and source divided by interior RMS of u_low",
        "operator": {
            "module": "solver.HelmholtzSolver",
            "equation_comment": "repository 2D FD/PML operator used by warm-start evaluator",
            "dx": cfg.dx,
            "sigma0_low": float(solver_l.sigma0),
            "sigma0_high": float(solver_h.sigma0),
            "pml_power": 2.0,
            "same_as_current_2d_eval": True,
        },
        "arrays": {
            "u_low_re": list(shape),
            "u_low_im": list(shape),
            "u_high_re": list(shape),
            "u_high_im": list(shape),
            "source_re": list(shape),
            "source_im": list(shape),
            "rms": [n_samples],
            "omega_low": [n_samples],
        },
        "source_distribution": {
            "n_sources": [cfg.min_sources, cfg.max_sources],
            "amplitude": [1.0, 2.0],
            "phase": [0.0, float(2.0 * np.pi)],
            "position_region": [cfg.npml, cfg.n - cfg.npml],
            "gaussian_sigma_grid_cells": cfg.source_sigma,
        },
        "sample_sources": source_meta,
    }
    (out_dir / "metadata.json").write_text(json.dumps(metadata, indent=2))
    (out_dir / "COMPLETE").write_text(f"complete {time.ctime()}\n")
    print(f"Dataset ready: {out_dir}", flush=True)
    return out_dir


def main() -> None:
    parser = argparse.ArgumentParser(formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    parser.add_argument("--pair", choices=["all", *PAIRS.keys()], default="32_64")
    parser.add_argument("--n_samples", type=int, default=200)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--out_root",
        type=Path,
        default=Path("/orcd/pool/006/fkiewiet/freq2transfer/datasets_fdpml_2d"),
    )
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    cfg = Data2DConfig(seed=args.seed)
    args.out_root.mkdir(parents=True, exist_ok=True)
    pairs = list(PAIRS) if args.pair == "all" else [args.pair]
    for pair_tag in pairs:
        generate_pair(pair_tag, args.n_samples, args.out_root, cfg, args.force)


if __name__ == "__main__":
    main()
