# ── static spatial channels ────────────────────────────────────────────────────
def _make_fourier_channels(n: int, k_bands: int = 6) -> np.ndarray:
    coords = np.linspace(0, 1, n, dtype=np.float32)
    X, Y = np.meshgrid(coords, coords, indexing="ij")
    ch = []
    for k in range(k_bands):
        f = 2 ** k * np.pi
        ch += [np.sin(f * X), np.cos(f * X), np.sin(f * Y), np.cos(f * Y)]
    return np.stack(ch, axis=0)

def _make_pml_map(n: int, npml: int) -> np.ndarray:
    ramp = np.zeros(n, dtype=np.float32)
    for i in range(npml):
        v = (npml - i) / npml
        ramp[i] = v; ramp[n - 1 - i] = v
    Xr, Yr = np.meshgrid(ramp, ramp, indexing="ij")
    return np.maximum(Xr, Yr)

_FOURIER  = _make_fourier_channels(GRID_N, k_bands=6)
_PML_MAP  = _make_pml_map(GRID_N, NPML)
_STATIC_T = torch.from_numpy(
    np.concatenate([_FOURIER, _PML_MAP[None]], axis=0)
).unsqueeze(0).to(DEVICE)   # (1, 25, 512, 512)


def build_input(inp_re: np.ndarray, inp_im: np.ndarray, omega: float) -> torch.Tensor:
    eta        = PML_SIGMA0[int(round(omega))]
    omega_norm = np.float32((omega - OMEGA_MIN) / (OMEGA_MAX - OMEGA_MIN))
    eta_norm   = np.float32((eta   - ETA_MIN)   / (ETA_MAX   - ETA_MIN))
    u_re_t = torch.from_numpy(inp_re[None, None]).to(DEVICE)
    u_im_t = torch.from_numpy(inp_im[None, None]).to(DEVICE)
    omega_f = torch.full((1, 1, GRID_N, GRID_N), omega_norm, device=DEVICE)
    eta_f   = torch.full((1, 1, GRID_N, GRID_N), eta_norm,   device=DEVICE)
    return torch.cat([u_re_t, u_im_t, _STATIC_T, omega_f, eta_f], dim=1)  # (1,29,H,W)


# ── model ──────────────────────────────────────────────────────────────────────
class ResBlock(nn.Module):
    def __init__(self, ch: int, norm_fn):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(ch, ch, 3, padding=1, bias=False), norm_fn(ch), nn.ReLU(inplace=True),
            nn.Conv2d(ch, ch, 3, padding=1, bias=False), norm_fn(ch),
        )
        self.relu = nn.ReLU(inplace=True)
    def forward(self, x): return self.relu(x + self.net(x))


class FrequencyTransferUNet(nn.Module):
    def __init__(self, in_ch=29, out_ch=2, base_ch=32, levels=4):
        super().__init__()
        chs = [min(base_ch * (2 ** i), 512) for i in range(levels + 1)]
        def _nf(lv):
            return partial(nn.InstanceNorm2d, affine=True) if lv <= 1 else partial(nn.GroupNorm, 8)
        self.stem = nn.Sequential(
            nn.Conv2d(in_ch, chs[0], 1, bias=False), _nf(0)(chs[0]), nn.ReLU(inplace=True))
        self.enc_blocks  = nn.ModuleList([ResBlock(chs[i], _nf(i)) for i in range(levels)])
        self.downsamples = nn.ModuleList([
            nn.Sequential(nn.Conv2d(chs[i], chs[i+1], 3, stride=2, padding=1, bias=False),
                          _nf(i+1)(chs[i+1]), nn.ReLU(inplace=True)) for i in range(levels)])
        self.bottleneck  = ResBlock(chs[levels], _nf(levels))
        self.upsamples   = nn.ModuleList([
            nn.Sequential(nn.Upsample(scale_factor=2, mode='bilinear', align_corners=False),
                          nn.Conv2d(chs[levels-i], chs[levels-i-1], 1, bias=False))
            for i in range(levels)])
        self.dec_merge   = nn.ModuleList([
            nn.Conv2d(chs[levels-i-1]*2, chs[levels-i-1], 1, bias=False) for i in range(levels)])
        self.dec_blocks  = nn.ModuleList([
            ResBlock(chs[levels-i-1], _nf(levels-i-1)) for i in range(levels)])
        self.head = nn.Conv2d(chs[0], out_ch, 1, bias=True)

    def forward(self, x):
        x = self.stem(x); skips = []
        for enc, down in zip(self.enc_blocks, self.downsamples):
            x = enc(x); skips.append(x); x = down(x)
        x = self.bottleneck(x)
        for up, merge, dec, skip in zip(self.upsamples, self.dec_merge,
                                         self.dec_blocks, reversed(skips)):
            x = dec(merge(torch.cat([up(x), skip], dim=1)))
        return self.head(x)


def load_unet(ckpt_path: Path) -> FrequencyTransferUNet:
    ckpt  = torch.load(ckpt_path, map_location=DEVICE, weights_only=False)
    args  = ckpt["args"]
    model = FrequencyTransferUNet(
        in_ch=29, out_ch=2,
        base_ch=args.get("base_ch", 32),
        levels=args.get("levels", 4),
    )
    state = {k.replace("_orig_mod.", ""): v for k, v in ckpt["model_state_dict"].items()}
    model.load_state_dict(state)
    return model.eval().to(DEVICE)


# ── data loading ───────────────────────────────────────────────────────────────
def get_test_raw_indices(n_per_pair: int = N_PER_PAIR) -> list[int]:
    """One raw dataset index per pair from the held-out test split."""
    n_total = 3 * n_per_pair
    n_tr    = int(0.70 * n_total)
    n_val   = int(0.15 * n_total)
    perm    = np.random.default_rng(GLOBAL_SEED).permutation(n_total)
    test    = perm[n_tr + n_val:]
    result  = []
    for pair in range(3):
        lo, hi   = pair * n_per_pair, (pair + 1) * n_per_pair
        pair_tst = [i for i in test if lo <= i < hi]
        result.append(pair_tst[10])
    return result


def load_raw(ds_path: Path, raw_idx: int):
    return (
        np.array(np.load(ds_path / "u_low_re.npy",  mmap_mode='r')[raw_idx], dtype=np.float32),
        np.array(np.load(ds_path / "u_low_im.npy",  mmap_mode='r')[raw_idx], dtype=np.float32),
        np.array(np.load(ds_path / "u_high_re.npy", mmap_mode='r')[raw_idx], dtype=np.float32),
        np.array(np.load(ds_path / "u_high_im.npy", mmap_mode='r')[raw_idx], dtype=np.float32),
        float(np.load(ds_path / "omega_low.npy",    mmap_mode='r')[raw_idx]),
    )


# ── metrics / inference ────────────────────────────────────────────────────────
def rel_l2(pred: np.ndarray, tgt: np.ndarray) -> float:
    p = pred[SL, SL].ravel(); t = tgt[SL, SL].ravel()
    return float(np.linalg.norm(p - t) / (np.linalg.norm(t) + 1e-8) * 100)

@torch.no_grad()
def infer(model, inp): return model(inp).cpu().numpy()[0]   # (2,H,W)


